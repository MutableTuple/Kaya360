#!/usr/bin/env node
// One-command local setup: starts local Supabase (Docker), writes .env.local
// automatically, creates an admin login, then starts the app on :3000.
import { execSync, spawn } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { randomBytes } from "node:crypto";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
process.chdir(root);
const ADMIN_EMAIL = process.env.KAYA_ADMIN_EMAIL || "admin@kaya.local";
const ADMIN_PASSWORD = process.env.KAYA_ADMIN_PASSWORD || "Kaya@Admin2026";
const step = (m) => console.log(`\n\x1b[36m▶ ${m}\x1b[0m`);
const fail = (m) => { console.error(`\n\x1b[31m✖ ${m}\x1b[0m\n`); process.exit(1); };
const run = (cmd, opts = {}) => execSync(cmd, { stdio: "inherit", shell: true, ...opts });
const capture = (cmd) => execSync(cmd, { encoding: "utf8", shell: true, stdio: ["ignore", "pipe", "pipe"] });

const [maj] = process.versions.node.split(".").map(Number);
if (maj < 20) fail(`Node.js 20+ is required (you have ${process.versions.node}). Install it from https://nodejs.org`);
try { capture("docker info"); } catch { fail("Docker is not running. Install Docker Desktop (https://www.docker.com/products/docker-desktop), start it, wait until it says 'Engine running', then run this again."); }

if (!existsSync("node_modules")) { step("Installing dependencies (first run only)…"); run("npm install --no-audit --no-fund"); }

step("Starting local Supabase database, auth and storage (first run downloads ~1–2 GB, please wait)…");
try { run("npx --yes supabase@latest start"); } catch { fail("Supabase failed to start. Check Docker Desktop is running and ports 54321–54324 are free, then retry."); }

step("Reading local keys…");
let status = "";
try { status = capture("npx --yes supabase@latest status -o env"); } catch (e) { fail(`Could not read Supabase status: ${e.message}`); }
const kv = Object.fromEntries([...status.matchAll(/^([A-Z_]+)="?([^"\r\n]*)"?/gm)].map((m) => [m[1], m[2]]));
const url = kv.API_URL || "http://127.0.0.1:54321";
const anon = kv.ANON_KEY || kv.PUBLISHABLE_KEY;
const service = kv.SERVICE_ROLE_KEY || kv.SECRET_KEY;
if (!anon || !service) fail("Could not find the anon/service keys in `supabase status` output.");

step("Writing .env.local…");
const keep = existsSync(".env.local") ? readFileSync(".env.local", "utf8") : "";
const old = Object.fromEntries([...keep.matchAll(/^([A-Z_]+)=(.*)$/gm)].map((m) => [m[1], m[2]]));
const env = {
  ...old,
  NEXT_PUBLIC_SUPABASE_URL: url, NEXT_PUBLIC_SUPABASE_ANON_KEY: anon, SUPABASE_SERVICE_ROLE_KEY: service,
  NEXT_PUBLIC_APP_URL: "http://localhost:3000",
  APP_ENCRYPTION_KEY: old.APP_ENCRYPTION_KEY || randomBytes(36).toString("base64url"),
  CRON_SECRET: old.CRON_SECRET || randomBytes(24).toString("base64url"),
};
writeFileSync(".env.local", "# Generated by scripts/local-setup.mjs — add API keys (OPENAI_API_KEY, SERPER_API_KEY, HUNTER_API_KEY…) below or in Settings → Integrations\n" + Object.entries(env).map(([k, v]) => `${k}=${v}`).join("\n") + "\n");

step("Creating admin login…");
const admin = await fetch(`${url}/auth/v1/admin/users`, {
  method: "POST", headers: { apikey: service, Authorization: `Bearer ${service}`, "Content-Type": "application/json" },
  body: JSON.stringify({ email: ADMIN_EMAIL, password: ADMIN_PASSWORD, email_confirm: true, user_metadata: { full_name: "Kaya Administrator" } }),
});
if (admin.ok) console.log(`  Created ${ADMIN_EMAIL}`);
else { const t = await admin.text(); if (/already|exists|registered/i.test(t)) console.log(`  ${ADMIN_EMAIL} already exists`); else console.warn(`  Could not create admin automatically: ${t.slice(0, 200)}`); }

console.log(`
\x1b[32m✔ Ready.\x1b[0m
  App:       http://localhost:3000
  Login:     ${ADMIN_EMAIL}  /  ${ADMIN_PASSWORD}
  Database:  http://127.0.0.1:54323  (Supabase Studio)
  Test mail: http://127.0.0.1:54324  (invitation & reset emails land here)
  Stop DB later with:  npx supabase stop
`);
step("Starting the app (Ctrl+C to stop)…");
spawn("npm", ["run", "dev"], { stdio: "inherit", shell: true });
